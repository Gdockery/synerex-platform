var Moment = require('moment-timezone');

module.exports = {

  friendlyName: 'Process new meter device ID',


  description: 'Upon creating a new meter (or updating an existing one), ensure that the device ID has a related PiBoard record and handle any existing MeterData records with the PiBoard\'s mesh ID.',


  inputs: {

    theMeter: {
      description: 'The new or updated Meter record',
      example: {}
    }

  },


  fn: function(inputs, exits) {
    //console.log("inputs: " + inputs);

    var theMeter = inputs.theMeter;

    //console.log("inputs.theMeter: " + inputs.theMeter);
    //console.log("inputs.theMeter.deviceId: " + inputs.theMeter.deviceId);

    // See if there is any PiBoard recorded with the new Meter's Pi-board serial #.
    PiBoard.findOne({
      deviceId: theMeter.deviceId
    }).exec(function(err, piBoard) {
      if (err) {
        return exits.error(err);
      }

      // If not, then the meter is not online yet (this should be the norm), so we'll just return
      // through the `success` exit generated by `buildCreateAction`.
      if (!piBoard) {
        return exits.success({
          response: {
            id: theMeter.id
          }
        });
      }

      // If so, first update the new meter with the PiBoard's mesh ID.
      Meter.update({
        id: theMeter.id
      }, {
        meshId: piBoard.meshId
      }).exec(function(err) {
        if (err) {
          return exits.error(err);
        }

        var now = new Date().getTime();

        // Get all of the MeterData rows with this mesh ID whose `meter` is `null`.
        // Note: could do this and the next step in a single query w/ subqueries,
        // but the subqueries would not use the indexes, so it's more efficient to split it into two.
        sails.getDatastore().sendNativeQuery('SELECT MAX(id) as id FROM ' + MeterData.tableName + ' WHERE meter IS NULL AND meshID=\'' + piBoard.meshId + '\' GROUP BY recordedAt').exec(function(err, result) {
          if (err) {
            return exits.error(err);
          }

          var rows = result.rows;
          var ids = _.pluck(rows, 'id');

          // Update any MeterData rows with the given mesh ID (and no meter ID) to match the new meter,
          // and update `createdAt` so that the rollup app will process the rows.  Limit the updates to one
          MeterData.update({
              id: ids
            }, {
              meter: theMeter.id,
              createdAt: now
            })
            .meta({
              fetch: true
            })
            .exec(function(err, updatedRows) {
              if (err) {
                return exits.error(err);
              }

              // Now that we've updated the meter data rows with the new Meter ID, we also need to calculate the correct
              // day, minute and interval for the entries based on the project's time zone.
              Project.findOne({
                id: theMeter.project
              }).exec(function(err, project) {
                if (err) {
                  return exits.error(err);
                }

                async.each(updatedRows, function(meterDataRow, nextMeterDataRow) {

                  // Get the time-zone adjusted moment that the recording was taken.
                  var recordedAtMoment = (new Moment(meterDataRow.recordedAt)).tz(project.timeZoneId);
                  var data = {};
                  // Get the day of the recording.
                  data.day = recordedAtMoment.format('YYYY-MM-DD') || '';
                  // Get the interval ID of the recording.
                  data.intervalId = sails.helpers.util.getIntervalFromMoment({
                    moment: recordedAtMoment
                  }).execSync() || '';
                  // Get the minute of the recording.
                  data.minute = recordedAtMoment.minute() || 0;

                  // Update the row.
                  MeterData.update({
                    id: meterDataRow.id
                  }, data).exec(nextMeterDataRow);


                }, function(err) {

                  // Finally delete any remaining MeterData rows with that mesh ID and `null` meter; these would
                  // be duplicate rows.
                  MeterData.destroy({
                    meshId: piBoard.meshId,
                    meter: null
                  }).exec(function(err) {
                    if (err) {
                      return exits.error(err);
                    }

                    // Return through the success exit.
                    return exits.success();

                  });

                });

              });

            });

        });

      });

    });

  }


};
