module.exports = {

  machine: {


    friendlyName: 'Reset password',


    description: 'Consume the provided password token, encrypt+set the new password, and log the user in.',


    inputs: {

      token: {
        description: 'The password token that was generated by the `sendPasswordRecoveryEmail` endpoint.',
        example: 'gwa8gs8hgw9h2g9hg29hgwh9asdgh9q34$$$$$asdgasdggds',
        required: true
      },

      password: {
        description: 'The new, unencrypted password.',
        example: 'abc123-v2',
        required: true
      }

    },


    exits: {

      success: {
        statusCode: 200
      },

      invalidToken: {
        statusCode: 404,
        description: 'The provided password token is invalid, or has already been used.',
      }

    },


    fn: function(inputs, exits) {
      var req = this.req;

      var bcrypt = require('bcryptjs');

      //  ╦╔╗╔╔═╗╦ ╦╔╦╗  ┬  ┬┌─┐┬  ┬┌┬┐┌─┐┌┬┐┬┌─┐┌┐┌┌─┐
      //  ║║║║╠═╝║ ║ ║   └┐┌┘├─┤│  │ ││├─┤ │ ││ ││││└─┐
      //  ╩╝╚╝╩  ╚═╝ ╩    └┘ ┴ ┴┴─┘┴─┴┘┴ ┴ ┴ ┴└─┘┘└┘└─┘
      // Strictly validate the password.
      // (Remember: it should have already been validated by front-end code)
      if (sails.helpers.web.auth && sails.helpers.web.auth.validateUserPassword) {
        try {
          sails.helpers.web.auth.validateUserPassword({
            string: inputs.password
          }).execSync();
        } catch (e) {
          switch (e.exit) {
            case undefined:
            case 'error':
              return exits.error(new Error('Consistency violation: Unexpected internal error (i.e. bug in our code) when validating the provided password.  Details: '+e.stack));
            default:
              return exits.error(new Error('Server-side validation failed for provided password.  This should NEVER happen in normal use (because it SHOULD have been validated/coerced on the front-end).  So, either there is a bug somewhere (potentially in our front-end code), or this is a deliberate poke at our API from a curious individual.  Details: '+e.stack));
          }
        }
      }

      //  ╔═╗╦╔╗╔╔╦╗  ┌┬┐┬ ┬┌─┐  ┬─┐┌─┐┌─┐┌─┐┌┬┐  ┌┬┐┌─┐┬┌─┌─┐┌┐┌
      //  ╠╣ ║║║║ ║║   │ ├─┤├┤   ├┬┘├┤ └─┐├┤  │    │ │ │├┴┐├┤ │││
      //  ╚  ╩╝╚╝═╩╝   ┴ ┴ ┴└─┘  ┴└─└─┘└─┘└─┘ ┴    ┴ └─┘┴ ┴└─┘┘└┘
      User.findOne({
        resetPasswordToken: inputs.token
      })
      .exec(function(err, user) {
        if(err) {
          return exits.error(err);
        }

        // If a user doesn't exist with that token, it's invalid
        if(!user) {
          return exits.invalidToken();
        }

        //  ╔═╗╔╗╔╔═╗╦═╗╦ ╦╔═╗╔╦╗  ┌─┐┌─┐┌─┐┌─┐┬ ┬┌─┐┬─┐┌┬┐
        //  ║╣ ║║║║  ╠╦╝╚╦╝╠═╝ ║   ├─┘├─┤└─┐└─┐││││ │├┬┘ ││
        //  ╚═╝╝╚╝╚═╝╩╚═ ╩ ╩   ╩   ┴  ┴ ┴└─┘└─┘└┴┘└─┘┴└──┴┘
        bcrypt.hash(inputs.password, 8, function(err, encryptedPassword) {
          if(err) {
            return exits.error(new Error('Cannot encrypt password.  Details: '+err.stack));
          }

          // Try to update the user record and consume the password reset token.
          User.update({
            id: user.id
          })
          .set({
            hashedPassword: encryptedPassword,
            resetPasswordToken: ''
          })
          .exec(function(err) {
            if(err) {
              return exits.error(err);
            }

            //  ╦  ╔═╗╔═╗╦╔╗╔  ┬ ┬┌─┐┌─┐┬─┐
            //  ║  ║ ║║ ╦║║║║  │ │└─┐├┤ ├┬┘
            //  ╩═╝╚═╝╚═╝╩╝╚╝  └─┘└─┘└─┘┴└─
            // Stores the user id in the session
            req.session.userId = user.id;

            return exits.success();

          }); // </ User.update(); >

        }); // </ bcrypt.hash(); >

      }); // </ User.findOne(); >

    }

  }

};
